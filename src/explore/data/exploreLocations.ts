// ─── VENUE LOCATIONS (Convert from venues data) ──────────────────────────────

import { VENUE_CATEGORIES, VENUE_SEO_DESCRIPTIONS, VenueItem, VenueCategory } from '../../data/venues/venuesData';
import { VENUE_COORDINATES } from '../../data/venues/venueCoordinates';

function venueToExploreLocation(
  venue: VenueItem,
  category: VenueCategory,
): ExploreLocationData | null {
  const coords = VENUE_COORDINATES[venue.id] || venue.coordinates;
  if (!coords) return null;

  const categoryMap: Record<string, ExploreLocationData['category']> = {
    'restaurants': 'Restaurant',
    'beach-clubs': 'Beach Club',
    'night-clubs': 'Nightlife',
    'dining-entertainment': 'Nightlife',
  };

  const priceMap: Record<string, 1 | 2 | 3 | 4> = {
    '$': 1,
    '$$': 2,
    '$$$': 3,
    '$$$$': 4,
  };

  const heroImageMap: Record<string, string> = {
    'restaurants': '/images/restaurants',
    'beach-clubs': '/images/beach_clubs',
    'night-clubs': '/images/nightclubs',
    'dining-entertainment': '/images/dining_entertainment',
  };

  const folderName = venue.name.replace(/[^a-zA-Z0-9]/g, '_');
  const heroImage = `${heroImageMap[category.id]}/${folderName}/image1.jpg`;

  return {
    id: `venue-${venue.id}`,
    name: venue.name,
    short_description: VENUE_SEO_DESCRIPTIONS[venue.id] || venue.vibe || 'A premier Dubai venue.',
    latitude: coords.lat,
    longitude: coords.lng,
    emirate: 'Dubai',
    area: venue.location,
    category: categoryMap[category.id] || 'Restaurant',
    subcategory: venue.tags?.[0],
    is_hidden_gem: false,
    is_featured: !!venue.trending,
    hero_image: heroImage,
    gallery_images: [],
    tags: venue.tags || [],
    vibe: venue.vibe,
    price_tier: priceMap[venue.priceRange] || 2,
    source_venue_id: venue.id,
  };
}

export const VENUE_EXPLORE_LOCATIONS: ExploreLocationData[] = VENUE_CATEGORIES.flatMap((cat) =>
  cat.items
    .map((venue) => venueToExploreLocation(venue, cat))
    .filter((loc): loc is ExploreLocationData => loc !== null),
);

