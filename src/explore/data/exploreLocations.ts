// ─── SQL SEED GENERATOR ───────────────────────────────────────────────────────

export function generateSeedSQL(): string {
  const escapeStr = (s: string | undefined | null): string => {
    if (!s) return 'NULL';
    return `'${s.replace(/'/g, "''")}'`;
  };

  const escapeArr = (arr: string[]): string => {
    if (!arr.length) return "'{}'";
    return `'{${arr.map((s) => `"${s.replace(/"/g, '\\"')}"`).join(',')}}'`;
  };

  const lines = ALL_EXPLORE_LOCATIONS.map((loc) => {
    return `INSERT INTO public.explore_locations (
  id, name, short_description, long_description, latitude, longitude, emirate, area, category, subcategory,
  is_hidden_gem, is_featured, hero_image, gallery_images, tags, vibe, price_tier, opening_hours, best_time, insider_tip, source_venue_id
) VALUES (
  ${escapeStr(loc.id)}, ${escapeStr(loc.name)}, ${escapeStr(loc.short_description)}, ${escapeStr(loc.long_description)},
  ${loc.latitude}, ${loc.longitude}, ${escapeStr(loc.emirate)}, ${escapeStr(loc.area)}, ${escapeStr(loc.category)}, ${escapeStr(loc.subcategory)},
  ${loc.is_hidden_gem}, ${loc.is_featured}, ${escapeStr(loc.hero_image)}, ${escapeArr(loc.gallery_images)}, ${escapeArr(loc.tags)},
  ${escapeStr(loc.vibe)}, ${loc.price_tier}, ${escapeStr(loc.opening_hours)}, ${escapeStr(loc.best_time)}, ${escapeStr(loc.insider_tip)}, ${escapeStr(loc.source_venue_id)}
) ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  short_description = EXCLUDED.short_description,
  latitude = EXCLUDED.latitude,
  longitude = EXCLUDED.longitude,
  tags = EXCLUDED.tags,
  updated_at = now();`;
  });

  return `-- ==========================================
-- EXPLORE LOCATIONS SEED DATA
-- Generated: ${new Date().toISOString()}
-- Total locations: ${ALL_EXPLORE_LOCATIONS.length}
-- ==========================================

${lines.join('\n\n')}`;
}
